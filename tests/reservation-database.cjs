function report(name, fn) {
    return fn().then(() => console.log(`PASS ${name}`)).catch((error) => {
        failures += 1;
        console.error(`FAIL ${name}: ${error.message}`);
    });
}

async function expectCode(promise, code) {
    let thrown;
    try { await promise; } catch (error) { thrown = error; }
    assert.ok(thrown, `expected PostgreSQL error ${code}, but statement succeeded`);
    assert.equal(thrown.code, code, `expected ${code}, got ${thrown.code || thrown.message}`);
}

